#!/usr/bin/env python3
"""Convert a PSF1/PSF2 console font to a C header.

Usage: psf2c.py <font.psf[.gz]> <out.h>

Only 8-pixel-wide fonts are supported, since the framebuffer console
renders one byte per glyph row. The first 256 glyphs are emitted; the
console only ever indexes with ASCII so the upper half is just there to
keep indexing unconditional.
"""

import gzip
import sys

PSF1_MAGIC = b"\x36\x04"
PSF2_MAGIC = b"\x72\xb5\x4a\x86"


def load(path):
    data = open(path, "rb").read()
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    return data


def parse(data):
    if data[:2] == PSF1_MAGIC:
        charsize = data[3]
        glyphs = [data[4 + i * charsize:4 + (i + 1) * charsize]
                  for i in range(256)]
        return 8, charsize, glyphs
    if data[:4] == PSF2_MAGIC:
        hdrsize = int.from_bytes(data[8:12], "little")
        numglyph = int.from_bytes(data[16:20], "little")
        charsize = int.from_bytes(data[20:24], "little")
        height = int.from_bytes(data[24:28], "little")
        width = int.from_bytes(data[28:32], "little")
        if width != 8 or charsize != height:
            sys.exit(f"unsupported PSF2 geometry: {width}x{height}")
        glyphs = []
        for i in range(256):
            if i < numglyph:
                off = hdrsize + i * charsize
                glyphs.append(data[off:off + charsize])
            else:
                glyphs.append(b"\x00" * charsize)
        return width, height, glyphs
    sys.exit("not a PSF font")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    width, height, glyphs = parse(load(sys.argv[1]))
    with open(sys.argv[2], "w") as f:
        f.write("/* Generated by tools/psf2c.py from %s. Do not edit. */\n"
                % sys.argv[1].split("/")[-1])
        f.write("#ifndef FONT8X16_H\n#define FONT8X16_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("#define FONT_WIDTH  %d\n" % width)
        f.write("#define FONT_HEIGHT %d\n\n" % height)
        f.write("static const uint8_t font8x16[256][%d] = {\n" % height)
        for i, g in enumerate(glyphs):
            rows = ", ".join("0x%02x" % b for b in g)
            f.write("    { %s },%s\n"
                    % (rows, " /* 0x%02x */" % i))
        f.write("};\n\n#endif\n")


if __name__ == "__main__":
    main()
